"""Validate private authentication settings before displaying any dashboard data."""
import copy
import math
import re


class AuthConfigurationError(ValueError):
    """Invalid private settings; messages must never include credential values."""


def validate_config(raw):
    if not isinstance(raw, dict):
        raise AuthConfigurationError('Authentication settings must be a mapping.')
    config = copy.deepcopy(raw)
    users = config.get('credentials', {}).get('usernames', {})
    if not isinstance(users, dict) or not users:
        raise AuthConfigurationError('Configure at least one dashboard user.')
    for username, user in users.items():
        if not isinstance(username, str) or not username or username != username.lower():
            raise AuthConfigurationError('Usernames must be nonempty and lowercase.')
        if not isinstance(user, dict) or not isinstance(user.get('name'), str) or not user['name'].strip():
            raise AuthConfigurationError('Each user must have a display name.')
        password = user.get('password', '')
        if not isinstance(password, str) or not re.fullmatch(r'\$2[aby]\$(?:0[4-9]|[12][0-9]|3[01])\$[./A-Za-z0-9]{53}', password):
            raise AuthConfigurationError('Each password must be a bcrypt hash generated by scripts/hash_password.py.')
    cookie = config.get('cookie', {})
    if not isinstance(cookie, dict):
        raise AuthConfigurationError('Cookie settings must be a mapping.')
    key = cookie.get('key', '')
    if not isinstance(key, str) or len(key) < 32 or key.startswith('REPLACE_'):
        raise AuthConfigurationError('Set a random cookie signing key of at least 32 characters.')
    name = cookie.get('name', 'riseboro_auth')
    if not isinstance(name, str) or not re.fullmatch(r'[A-Za-z0-9_-]+', name):
        raise AuthConfigurationError('Cookie name must contain only letters, digits, underscores or hyphens.')
    days = cookie.get('expiry_days', 1)
    if isinstance(days, bool) or not isinstance(days, (float, int)) or not math.isfinite(days) or not 0 <= days <= 30:
        raise AuthConfigurationError('Cookie expiry must be between 0 and 30 days.')
    config['cookie'] = {'name': name, 'key': key, 'expiry_days': days}
    return config
